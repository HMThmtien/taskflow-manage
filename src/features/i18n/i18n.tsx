const resources: Record<AppLocale, Dictionary> = {
  en,
  vi,
  "zh-CN": zhCN,
  ja,
  ko,
};

function getByPath(dict: Dictionary, path: string): string | Dictionary | undefined {
  return path.split(".").reduce<string | Dictionary | undefined>((acc, part) => {
    if (!acc || typeof acc === "string") return undefined;
    return acc[part];
  }, dict);
}

export function normalizeLocale(raw?: string | null): AppLocale {
  const value = (raw ?? "").trim().toLowerCase();
  if (value.startsWith("vi")) return "vi";
  if (value.startsWith("zh")) return "zh-CN";
  if (value.startsWith("ja")) return "ja";
  if (value.startsWith("ko")) return "ko";
  return "en";
}

function getInitialLocale(): AppLocale {
  try {
    const stored = localStorage.getItem(LOCALE_KEY);
    if (stored) return normalizeLocale(stored);
  } catch {}
  return normalizeLocale(navigator.language);
}

type I18nContextValue = {
  locale: AppLocale;
  setLocale: (locale: AppLocale) => void;
  t: (key: string, params?: Record<string, string | number | undefined | null>) => string;
  languages: { value: AppLocale; label: string }[];
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const isAuthed = useAuthStore((state) => !!state.tokens?.accessToken);
  const profileQuery = useMyProfileQuery(isAuthed);
  const [locale, setLocaleState] = useState<AppLocale>(getInitialLocale);
  const hydratedFromProfileRef = useRef(false);

  useEffect(() => {
    document.documentElement.lang = locale;
    try {
      localStorage.setItem(LOCALE_KEY, locale);
    } catch {}
  }, [locale]);

  useEffect(() => {
    if (!isAuthed || hydratedFromProfileRef.current || !profileQuery.data?.locale) return;
    hydratedFromProfileRef.current = true;
    setLocaleState(normalizeLocale(profileQuery.data.locale));
  }, [isAuthed, profileQuery.data?.locale]);

  const value = useMemo<I18nContextValue>(() => {
    const t = (key: string, params?: Record<string, string | number | undefined | null>) => {
      const raw = getByPath(resources[locale], key) ?? getByPath(resources.en, key);
      const template = typeof raw === "string" ? raw : key;
      return template.replace(/\{(\w+)\}/g, (_, token) => String(params?.[token] ?? ""));
    };

    return {
      locale,
      setLocale: setLocaleState,
      t,
      languages: supportedLocales.map((code) => ({
        value: code,
        label: t(`languages.${code}`),
      })),
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return ctx;
}
